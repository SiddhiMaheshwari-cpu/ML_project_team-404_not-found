from fastapi import FastAPI, HTTPException
from pydantic import BaseModel
import subprocess
import os
import shutil

app = FastAPI(title="Member 3 - Validation Sandbox API")

# Configuration for the isolated target repository workspace
REPO_DIR = "/content/target_repo"

class PatchRequest(BaseModel):
    patch_text: str
    test_command: str = "pytest"

def setup_workspace():
    """Task 1: Setup temporary clean repository clone/workspace"""
    if os.path.exists(REPO_DIR):
        shutil.rmtree(REPO_DIR)
    os.makedirs(REPO_DIR, exist_ok=True)

    # Initialize a mock target repo for testing (Replace with actual git clone if needed)
    subprocess.run(["git", "init", REPO_DIR], check=True)
    subprocess.run(["git", "config", "--global", "user.email", "devops@agent.com"], check=True)
    subprocess.run(["git", "config", "--global", "user.name", "Devops Agent"], check=True)

@app.on_event("startup")
def startup_event():
    setup_workspace()

@app.post("/validate-patch")
def validate_patch(data: PatchRequest):
    """
    Task 2 & 3 & 4: Receive patch, apply in sandbox, run tests with timeout, and return feedback.
    """
    patch_file_path = os.path.join(REPO_DIR, "solution.patch")

    # 1. Save patch file inside sandbox
    with open(patch_file_path, "w", encoding="utf-8") as f:
        f.write(data.patch_text)

    try:
        # 2. Apply patch using git apply
        apply_result = subprocess.run(
            ["git", "apply", "solution.patch"],
            cwd=REPO_DIR,
            capture_output=True,
            text=True
        )

        if apply_result.returncode != 0:
            # Revert any partial changes
            subprocess.run(["git", "checkout", "."], cwd=REPO_DIR)
            return {
                "status": "FAIL",
                "error_stage": "GIT_APPLY",
                "exit_code": apply_result.returncode,
                "log": f"Git Apply Failed:\n{apply_result.stderr}"
            }

        # 3. Run Auto-Test with a strict Timeout (Task 4: e.g., 60 seconds)
        test_result = subprocess.run(
            data.test_command,
            shell=True,
            cwd=REPO_DIR,
            capture_output=True,
            text=True,
            timeout=60 # Prevents infinite loops
        )

        # Revert changes after test run to keep workspace clean for next retry
        subprocess.run(["git", "checkout", "."], cwd=REPO_DIR)
        subprocess.run(["git", "clean", "-fd"], cwd=REPO_DIR)

        if test_result.returncode == 0:
            return {
                "status": "SUCCESS",
                "exit_code": 0,
                "log": "All tests passed successfully!"
            }
        else:
            return {
                "status": "FAIL",
                "error_stage": "TEST_EXECUTION",
                "exit_code": test_result.returncode,
                "log": test_result.stdout + "\n" + test_result.stderr
            }

    except subprocess.TimeoutExpired:
        # Task 4: Timeout handle for infinite loops
        subprocess.run(["git", "checkout", "."], cwd=REPO_DIR)
        return {
            "status": "FAIL",
            "error_stage": "TIMEOUT",
            "exit_code": -1,
            "log": "Test execution timed out after 60 seconds (Infinite loop suspected)."
        }
    except Exception as e:
        return {
            "status": "FAIL",
            "error_stage": "SYSTEM_ERROR",
            "exit_code": -1,
            "log": str(e)
        }

