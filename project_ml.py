import subprocess
import os

class ColabSandboxExecutor:
    def __init__(self, repo_dir: str):
        self.repo_dir = repo_dir

    def save_patch(self, patch_text: str, patch_filename: str = "patch.diff") -> str:
        """Saves unified diff string into a local patch file."""
        patch_path = os.path.join(self.repo_dir, patch_filename)
        with open(patch_path, "w", encoding="utf-8") as f:
            f.write(patch_text)
        return patch_path

    def apply_patch(self, patch_path: str) -> tuple[bool, str]:
        """Applies the git unified diff patch to the repository."""
        cmd = f"git -C {self.repo_dir} apply {patch_path}"
        result = subprocess.run(cmd, shell=True, capture_output=True, text=True)

        if result.returncode == 0:
            return True, "Patch applied cleanly."
        else:
            return False, f"Git Apply Error:\n{result.stderr}"

    def run_tests(self, test_command: str) -> tuple[int, str]:
        """Runs the failing test command inside the repository."""
        cmd = f"cd {self.repo_dir} && {test_command}"
        result = subprocess.run(cmd, shell=True, capture_output=True, text=True)

        logs = result.stdout + "\n" + result.stderr
        return result.returncode, logs

    def revert_changes(self):
        """Rolls back all uncommitted changes on failure for retry loops."""
        subprocess.run(f"git -C {self.repo_dir} checkout .", shell=True)
        subprocess.run(f"git -C {self.repo_dir} clean -fd", shell=True)

    def execute_patch_and_test(self, patch_text: str, test_command: str) -> dict:
        """
        Main execution controller interface for Member 1 (LangGraph Agent).
        """
        # Step 1: Save patch to file
        patch_file = self.save_patch(patch_text)

        # Step 2: Try applying the patch
        applied, apply_log = self.apply_patch(patch_file)
        if not applied:
            self.revert_changes()
            return {
                "status": "FAIL",
                "error_stage": "GIT_APPLY",
                "log": apply_log
            }

        # Step 3: Run the test suite
        exit_code, test_log = self.run_tests(test_command)

        # Step 4: Evaluate results & return feedback
        if exit_code == 0:
            return {
                "status": "SUCCESS",
                "log": "All tests passed cleanly!"
            }
        else:
            # Revert bad patch so LLM can try again on a fresh workspace
            self.revert_changes()
            return {
                "status": "FAIL",
                "error_stage": "TEST_EXECUTION",
                "log": test_log
            }

